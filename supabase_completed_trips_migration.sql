create table if not exists public.completed_trip_access (
    singleton boolean primary key default true check (singleton),
    user_id uuid not null unique references auth.users(id) on delete restrict
);

alter table public.completed_trip_access enable row level security;
alter table public.completed_trip_access no force row level security;
revoke all on table public.completed_trip_access from public, anon, authenticated;

do $$
declare
    intended_user_id uuid;
    configured_user_id uuid;
begin
    select id into intended_user_id
    from auth.users
    where lower(btrim(email)) = 'sceratoconcepts@gmail.com'
      and email_confirmed_at is not null;

    if intended_user_id is null then
        raise exception
            'Create and verify the sceratoconcepts@gmail.com Supabase account before applying this migration';
    end if;

    insert into public.completed_trip_access (singleton, user_id)
    values (true, intended_user_id)
    on conflict (singleton) do nothing;

    select user_id into configured_user_id
    from public.completed_trip_access
    where singleton;

    if configured_user_id is distinct from intended_user_id then
        raise exception
            'Completed Trip access is already bound to a different Supabase account ID';
    end if;
end;
$$;

create or replace function public.completed_trip_access_allowed()
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public, auth, pg_temp
as $$
    select auth.uid() is not null
       and exists (
           select 1
           from public.completed_trip_access
           where singleton and user_id = auth.uid()
       )
       and exists (
           select 1
           from auth.users as auth_user
           where auth_user.id = auth.uid()
             and lower(btrim(auth_user.email)) = 'sceratoconcepts@gmail.com'
             and auth_user.email_confirmed_at is not null
       );
$$;

revoke all on function public.completed_trip_access_allowed() from public, anon;
grant execute on function public.completed_trip_access_allowed() to authenticated;

create table if not exists public.completed_trips (
    id bigint generated by default as identity primary key,
    owner_id uuid not null references auth.users(id) on delete cascade,
    title text not null check (length(btrim(title)) between 1 and 200),
    starting_location text not null check (length(btrim(starting_location)) between 1 and 300),
    destination text not null check (length(btrim(destination)) between 1 and 300),
    departure_at timestamptz not null,
    arrival_at timestamptz not null,
    distance numeric(12, 2) not null check (distance > 0),
    distance_unit text not null check (distance_unit in ('km', 'mi')),
    duration_minutes integer generated always as (
        greatest(0, floor(extract(epoch from (arrival_at - departure_at)) / 60)::integer)
    ) stored,
    transportation_type text not null check (
        transportation_type in ('car', 'motorcycle', 'bus', 'train', 'airplane', 'other')
    ),
    notes text check (notes is null or length(notes) <= 5000),
    attachment_object_path text,
    attachment_mime_type text check (
        attachment_mime_type is null
        or attachment_mime_type in ('image/jpeg', 'image/png', 'image/webp')
    ),
    ism_no text,
    shipment_date date,
    origin text,
    route_number integer,
    truck_plate text,
    trailer_plate text,
    pallet_capacity integer,
    trip_rate numeric(12, 2),
    fuel_allocation numeric(12, 2),
    actual_fuel numeric(12, 2),
    time_in time without time zone,
    time_out time without time zone,
    load text,
    driver text,
    trip_fuel text,
    manifest_object_path text,
    manifest_mime_type text,
    fuel_receipt_object_path text,
    fuel_receipt_mime_type text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint completed_trips_arrival_after_departure
        check (arrival_at >= departure_at),
    constraint completed_trips_attachment_fields_together
        check (
            (attachment_object_path is null and attachment_mime_type is null)
            or (attachment_object_path is not null and attachment_mime_type is not null)
        )
);

