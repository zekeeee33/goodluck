update public.completed_trips
set ism_no = coalesce(ism_no, nullif(title, '')),
        shipment_date = coalesce(shipment_date, departure_at::date),
        origin = coalesce(origin, starting_location),
        time_in = coalesce(time_in, arrival_at::time),
        time_out = coalesce(time_out, departure_at::time),
        trip_fuel = coalesce(trip_fuel, notes),
        manifest_object_path = coalesce(manifest_object_path, attachment_object_path),
        manifest_mime_type = coalesce(manifest_mime_type, attachment_mime_type)
where shipment_date is null
   or ism_no is null
   or origin is null
   or (time_in is null and arrival_at is not null)
   or (time_out is null and departure_at is not null)
   or (trip_fuel is null and notes is not null)
   or (manifest_object_path is null and attachment_object_path is not null);

