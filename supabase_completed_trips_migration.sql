create or replace function public.prevent_completed_trip_owner_change()
returns trigger
language plpgsql
set search_path = pg_catalog, public, pg_temp
as $$
begin
    if new.owner_id is distinct from old.owner_id then
        raise exception 'Completed trip ownership cannot be changed';
    end if;
    new.updated_at := now();
    return new;
end;
$$;

drop trigger if exists completed_trips_owner_immutable on public.completed_trips;
create trigger completed_trips_owner_immutable
    before update on public.completed_trips
    for each row execute function public.prevent_completed_trip_owner_change();

