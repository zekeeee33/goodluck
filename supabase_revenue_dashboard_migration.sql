-- Run after supabase_route_trip_rate_migration.sql and
-- supabase_truck_trailer_migration.sql. Only administrator requests made by the
-- trusted Flask server can execute the granted revenue RPCs.

alter table public.trips
    add column if not exists revenue_status text not null default 'pending';

alter table public.trips
    drop constraint if exists trips_revenue_status_check;
alter table public.trips
    add constraint trips_revenue_status_check
    check (revenue_status in ('pending', 'eligible', 'cancelled'));

comment on column public.trips.revenue_status is
    'Management-controlled revenue recognition state; legacy trips default to pending.';

create table if not exists public.trip_revenue_status_history (
    id bigint generated by default as identity pr
    imary key,
    trip_id bigint not null references public.trips(id) on delete restrict,
    old_status text not null,
    new_status text not null,
    reason text not null,
    changed_by uuid not null references auth.users(id) on delete restrict,
    changed_at timestamptz not null default now(),
    constraint trip_revenue_status_history_status_check8
        check (old_status in ('pending', 'eligible', 'cancelled')
            and new_status in ('pending', 'eligible', 'cancelled'))
);

create index if not exists trip_revenue_status_history_trip_changed_idx
    on public.trip_revenue_status_history(trip_id, changed_at desc);

create table if not exists public.revenue_adjustments (
    id bigint generated by default as identity primary key,
    trip_id bigint not null references public.trips(id) on delete restrict,
    amount numeric(12, 2) not null check (amount <> 0),
    reason text not null check (length(trim(reason)) > 0),
    created_by uuid not null references auth.users(id) on delete restrict,
    created_at timestamptz not null default now(),
    idempotency_key uuid not null unique
);

create index if not exists revenue_adjustments_trip_created_idx
    on public.revenue_adjustments(trip_id, created_at, id);

alter table public.trip_revenue_status_history enable row level security;
alter table public.revenue_adjustments enable row level security;
revoke all on public.trip_revenue_status_history from public, anon, authenticated;
revoke all on public.revenue_adjustments from public, anon, authenticated;

