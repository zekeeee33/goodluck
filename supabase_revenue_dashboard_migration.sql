create or replace function public.set_trip_revenue_status(
    p_trip_id bigint,
    p_status text,
    p_reason text,
    p_actor_id uuid,
    p_actor_email text
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
    trip_row public.trips%rowtype;
    reason_text text := trim(coalesce(p_reason, ''));
begin
    if p_actor_id is null then
        raise exception 'Authenticated administrator identity is required';
    end if;
    if p_status is null or p_status not in ('pending', 'eligible', 'cancelled') then
        raise exception 'Revenue status must be pending, eligible, or cancelled';
    end if;
    if reason_text = '' then
        raise exception 'A reason is required for revenue status changes';
    end if;

    select * into trip_row
    from public.trips
    where id = p_trip_id
    for update;

    if not found then
        raise exception 'Trip % was not found', p_trip_id;
    end if;

    if p_status = 'eligible'
       and (
           trip_row.truck_route_rate is null
           or trip_row.truck_route_rate < 0
           or coalesce(trip_row.trip_rate_review_required, true)
           or coalesce(trip_row.trailer_review_required, true)
           or trip_row.pallet_capacity is null
       ) then
        raise exception 'Trip has no verified historical hauling-rate and trailer-capacity snapshot';
    end if;

    if trip_row.revenue_status = p_status then
        return to_jsonb(trip_row);
    end if;

    perform set_config('app.revenue_status_reason', reason_text, true);
    perform set_config('app.revenue_status_actor', p_actor_id::text, true);
    update public.trips
    set revenue_status = p_status,
        last_edited_by = p_actor_id,
        last_edited_by_email = nullif(trim(coalesce(p_actor_email, '')), '')
    where id = p_trip_id
    returning * into trip_row;

    return to_jsonb(trip_row);
end;
$$;

-- Capture the prior state before the update; the RPC sets this transaction-local value.
create or replace function public.log_trip_revenue_status_change()
returns trigger
language plpgsql
set search_path = pg_catalog, public, pg_temp
as $$
declare
    reason_value text := current_setting('app.revenue_status_reason', true);
    actor_value uuid := nullif(current_setting('app.revenue_status_actor', true), '')::uuid;
begin
    if new.revenue_status is distinct from old.revenue_status then
        if actor_value is null or nullif(trim(coalesce(reason_value, '')), '') is null then
            raise exception 'Revenue status changes must use the audited management workflow';
        end if;
        insert into public.trip_revenue_status_history (
            trip_id, old_status, new_status, reason, changed_by
        )
        values (
            new.id,
            old.revenue_status,
            new.revenue_status,
            reason_value,
            actor_value
        );
    end if;
    return new;
end;
$$;

drop trigger if exists trips_revenue_status_history on public.trips;
create trigger trips_revenue_status_history
    after update of revenue_status on public.trips
    for each row execute function public.log_trip_revenue_status_change();

-- The RPC uses the trip-row lock to serialize adjustments and make retries safe.
create or replace function public.add_revenue_adjustment(
    p_trip_id bigint,
    p_amount numeric,
    p_reason text,
    p_actor_id uuid,
    p_idempotency_key uuid
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
    trip_row public.trips%rowtype;
    existing_row public.revenue_adjustments%rowtype;
    adjustment_row public.revenue_adjustments%rowtype;
    reason_text text := trim(coalesce(p_reason, ''));
    current_adjustments numeric(12, 2);
begin
    if p_actor_id is null then
        raise exception 'Authenticated administrator identity is required';
    end if;
    if p_idempotency_key is null then
        raise exception 'An adjustment request identifier is required';
    end if;
    if p_amount is null or p_amount = 0 then
        raise exception 'Adjustment must be a non-zero amount';
    end if;
    if reason_text = '' then
        raise exception 'A reason is required for revenue adjustments';
    end if;

    select * into existing_row
    from public.revenue_adjustments
    where idempotency_key = p_idempotency_key;
    if found then
        if existing_row.trip_id <> p_trip_id
           or existing_row.amount <> p_amount
           or existing_row.reason <> reason_text
           or existing_row.created_by <> p_actor_id then
            raise exception 'Adjustment request identifier was already used for different details';
        end if;
        return to_jsonb(existing_row);
    end if;

    select * into trip_row
    from public.trips
    where id = p_trip_id
    for update;
    if not found then
        raise exception 'Trip % was not found', p_trip_id;
    end if;
    if trip_row.revenue_status <> 'eligible'
       or trip_row.truck_route_rate is null
       or trip_row.truck_route_rate < 0
       or coalesce(trip_row.trip_rate_review_required, true)
       or coalesce(trip_row.trailer_review_required, true)
       or trip_row.pallet_capacity is null then
        raise exception 'Only revenue-eligible trips with verified rate snapshots can be adjusted';
    end if;

    select coalesce(sum(amount), 0)
    into current_adjustments
    from public.revenue_adjustments
    where trip_id = p_trip_id;
    if trip_row.truck_route_rate + current_adjustments + p_amount < 0 then
        raise exception 'Adjustment cannot reduce recognized trip revenue below zero';
    end if;

    insert into public.revenue_adjustments (
        trip_id, amount, reason, created_by, idempotency_key
    )
    values (
        p_trip_id, p_amount, reason_text, p_actor_id, p_idempotency_key
    )
    on conflict (idempotency_key) do nothing
    returning * into adjustment_row;

    if not found then
        select * into existing_row
        from public.revenue_adjustments
        where idempotency_key = p_idempotency_key;
        if existing_row.trip_id <> p_trip_id
           or existing_row.amount <> p_amount
           or existing_row.reason <> reason_text
           or existing_row.created_by <> p_actor_id then
            raise exception 'Adjustment request identifier was already used for different details';
        end if;
        return to_jsonb(existing_row);
    end if;
    return to_jsonb(adjustment_row);
end;
$$;

create or replace function public.revenue_dashboard(
    p_start_date date,
    p_end_date date,
    p_origin text default null,
    p_destination text default null,
    p_route_number integer default null,
    p_driver_id bigint default null,
    p_truck_id bigint default null,
    p_trailer_id bigint default null,
    p_pallet_capacity integer default null,
    p_search text default null,
    p_page integer default 1,
    p_page_size integer default 25,
    p_sort_by text default 'shipment_date',
    p_sort_dir text default 'desc',
    p_bucket text default 'day'
)
returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
    previous_days integer;
    previous_start date;
    previous_end date;
    output jsonb;
begin
    if p_start_date is null or p_end_date is null or p_start_date > p_end_date then
        raise exception 'Start date must be on or before end date';
    end if;
    if p_page < 1 or p_page_size < 1 or p_page_size > 100 then
        raise exception 'Invalid revenue ledger page';
    end if;
    if p_sort_by not in ('shipment_date', 'id', 'revenue', 'route') then
        raise exception 'Invalid revenue ledger sort column';
    end if;
    if p_sort_dir not in ('asc', 'desc') then
        raise exception 'Invalid revenue ledger sort direction';
    end if;
    if p_bucket not in ('day', 'week', 'month') then
        raise exception 'Invalid revenue trend bucket';
    end if;

    previous_days := p_end_date - p_start_date + 1;
    previous_start := p_start_date - previous_days;
    previous_end := p_start_date - 1;

    with candidate_trips as (
        select
            trip.id,
            trip.shipment_date,
            trip.ism_no,
            trip.origin,
            trip.destination,
            trip.route_number,
            trip.route_pair,
            trip.driver_id,
            driver.name as driver_name,
            coalesce(trip.truck_id, trip.vehicle_id) as truck_id,
            coalesce(truck.plate_number, trip.plate_no) as truck_plate_number,
            trip.trailer_id,
            trailer.plate_number as trailer_plate_number,
            trip.pallet_capacity,
            trip.truck_route_rate,
            trip.revenue_status,
            (
                trip.revenue_status <> 'cancelled'
                and trip.truck_route_rate is not null
                and trip.truck_route_rate >= 0
                and not coalesce(trip.trip_rate_review_required, true)
                and not coalesce(trip.trailer_review_required, true)
                and trip.pallet_capacity is not null
            ) as is_revenue_eligible
        from public.trips as trip
        left join public.drivers as driver on driver.id = trip.driver_id
        left join public.vehicles as truck on truck.id = coalesce(trip.truck_id, trip.vehicle_id)
        left join public.trailers as trailer on trailer.id = trip.trailer_id
        where trip.shipment_date between previous_start and p_end_date
          and (nullif(trim(coalesce(p_origin, '')), '') is null or trip.origin = p_origin)
          and (nullif(trim(coalesce(p_destination, '')), '') is null or trip.destination = p_destination)
          and (p_route_number is null or trip.route_number = p_route_number)
          and (p_driver_id is null or trip.driver_id = p_driver_id)
          and (p_truck_id is null or coalesce(trip.truck_id, trip.vehicle_id) = p_truck_id)
          and (p_trailer_id is null or trip.trailer_id = p_trailer_id)
          and (p_pallet_capacity is null or trip.pallet_capacity = p_pallet_capacity)
          and (
              nullif(trim(coalesce(p_search, '')), '') is null
              or coalesce(trip.ism_no, '') ilike '%' || trim(p_search) || '%'
              or coalesce(trip.origin, '') ilike '%' || trim(p_search) || '%'
              or coalesce(trip.destination, '') ilike '%' || trim(p_search) || '%'
              or coalesce(driver.name, '') ilike '%' || trim(p_search) || '%'
              or coalesce(truck.plate_number, trip.plate_no, '') ilike '%' || trim(p_search) || '%'
              or coalesce(trailer.plate_number, '') ilike '%' || trim(p_search) || '%'
          )
    ),
    adjustment_totals as (
        select
            adjustment.trip_id,
            sum(adjustment.amount)::numeric(14, 2) as adjustment_total,
            jsonb_agg(jsonb_build_object(
                'id', adjustment.id,
                'amount', adjustment.amount,
                'reason', adjustment.reason,
                'created_at', adjustment.created_at,
                'created_by', adjustment.created_by
            ) order by adjustment.created_at, adjustment.id) as adjustment_details
        from public.revenue_adjustments as adjustment
        join candidate_trips as candidate on candidate.id = adjustment.trip_id
        group by adjustment.trip_id
    ),
    period_trips as (
        select
            candidate.*,
            coalesce(adjustments.adjustment_total, 0)::numeric(14, 2) as adjustment_total,
            coalesce(adjustments.adjustment_details, '[]'::jsonb) as adjustment_details
        from candidate_trips as candidate
        left join adjustment_totals as adjustments on adjustments.trip_id = candidate.id
    ),
    current_trips as (
        select * from period_trips
        where shipment_date between p_start_date and p_end_date
    ),
    previous_trips as (
        select * from period_trips
        where shipment_date between previous_start and previous_end
    ),
    current_eligible as (
        select * from current_trips where is_revenue_eligible
    ),
    previous_eligible as (
        select * from previous_trips where is_revenue_eligible
    ),
    current_summary as (
        select
            coalesce(sum(truck_route_rate + adjustment_total), 0)::numeric(14, 2) as total_revenue,
            count(*)::bigint as eligible_trips
        from current_eligible
    ),
    previous_summary as (
        select
            coalesce(sum(truck_route_rate + adjustment_total), 0)::numeric(14, 2) as total_revenue,
            count(*)::bigint as eligible_trips
        from previous_eligible
    ),
    route_stats as (
        select
            coalesce(route_pair, concat(coalesce(origin, 'Unknown'), ' → ', coalesce(destination, 'Unknown'))) as route_label,
            route_number,
            origin,
            destination,
            sum(truck_route_rate + adjustment_total)::numeric(14, 2) as revenue,
            count(*)::bigint as trips
        from current_eligible
        group by route_pair, route_number, origin, destination
    ),
    driver_stats as (
        select
            driver_id,
            coalesce(driver_name, 'Unassigned driver') as driver_name,
            sum(truck_route_rate + adjustment_total)::numeric(14, 2) as revenue,
            count(*)::bigint as trips
        from current_eligible
        group by driver_id, driver_name
    ),
    capacity_stats as (
        select
            pallet_capacity,
            sum(truck_route_rate + adjustment_total)::numeric(14, 2) as revenue,
            count(*)::bigint as trips
        from current_eligible
        group by pallet_capacity
    ),
    trend_stats as (
        select
            date_trunc(p_bucket, shipment_date::timestamp)::date as bucket_date,
            sum(truck_route_rate + adjustment_total)::numeric(14, 2) as revenue,
            count(*)::bigint as trips
        from current_eligible
        group by date_trunc(p_bucket, shipment_date::timestamp)::date
    ),
    truck_stats as (
        select
            truck_id,
            coalesce(truck_plate_number, 'Unassigned truck') as truck_plate_number,
            sum(truck_route_rate + adjustment_total)::numeric(14, 2) as revenue,
            count(*)::bigint as trips
        from current_eligible
        group by truck_id, truck_plate_number
    ),
    trailer_stats as (
        select
            trailer_id,
            coalesce(trailer_plate_number, 'Unassigned trailer') as trailer_plate_number,
            sum(truck_route_rate + adjustment_total)::numeric(14, 2) as revenue,
            count(*)::bigint as trips
        from current_eligible
        group by trailer_id, trailer_plate_number
    ),
    truck_trailer_stats as (
        select
            truck_id,
            coalesce(truck_plate_number, 'Unassigned truck') as truck_plate_number,
            trailer_id,
            coalesce(trailer_plate_number, 'Unassigned trailer') as trailer_plate_number,
            sum(truck_route_rate + adjustment_total)::numeric(14, 2) as revenue,
            count(*)::bigint as trips
        from current_eligible
        group by truck_id, truck_plate_number, trailer_id, trailer_plate_number
    ),
    fuel_stats as (
        select
            coalesce(sum(coalesce(actual_expense, total_cost)), 0)::numeric(14, 2) as recorded_cost,
            count(*)::bigint as log_count,
            count(*) filter (where actual_expense is null and total_cost is null)::bigint as missing_cost_count
        from public.fuel_logs
        where logged_on between p_start_date and p_end_date
          and (p_truck_id is null or vehicle_id = p_truck_id)
    ),
    maintenance_stats as (
        select
            coalesce(sum(cost), 0)::numeric(14, 2) as recorded_cost,
            count(*)::bigint as record_count
        from public.maintenance
        where performed_on between p_start_date and p_end_date
          and (p_truck_id is null or vehicle_id = p_truck_id)
    ),
    payroll_item_ranked as (
        select
            item.trip_id,
            item.rate,
            row_number() over (
                partition by item.trip_id
                order by
                    (period.status = 'finalized') desc,
                    coalesce(period.finalized_at, period.reviewed_at, period.created_at) desc,
                    item.id desc
            ) as item_rank
        from public.payroll_items as item
        join public.payroll_periods as period on period.id = item.payroll_period_id
        join current_trips as trip on trip.id = item.trip_id
        where period.status in ('reviewed', 'finalized')
          and item.trip_date between p_start_date and p_end_date
    ),
    payroll_stats as (
        select
            coalesce(sum(rate) filter (where item_rank = 1), 0)::numeric(14, 2) as recorded_cost,
            count(*) filter (where item_rank = 1)::bigint as recorded_trip_count
        from payroll_item_ranked
    ),
    recent_trips as (
        select
            id,
            shipment_date,
            ism_no,
            origin,
            destination,
            route_number,
            route_pair,
            driver_id,
            driver_name,
            truck_id,
            truck_plate_number,
            trailer_id,
            trailer_plate_number,
            case when is_revenue_eligible
                then (truck_route_rate + adjustment_total)::numeric(14, 2)
                else 0::numeric(14, 2)
            end as recognized_revenue
        from current_trips
        order by shipment_date desc, id desc
        limit 10
    ),
    ledger_match as (
        select
            *,
            case when is_revenue_eligible
                then (truck_route_rate + adjustment_total)::numeric(14, 2)
                else 0::numeric(14, 2)
            end as recognized_revenue,
            coalesce(route_pair, concat(coalesce(origin, 'Unknown'), ' → ', coalesce(destination, 'Unknown'))) as route_label
        from current_trips
    ),
    ledger_count as (
        select count(*)::bigint as total from ledger_match
    ),
    ledger_page as (
        select *
        from ledger_match
        order by
            case when p_sort_by = 'shipment_date' and p_sort_dir = 'asc' then shipment_date end asc,
            case when p_sort_by = 'shipment_date' and p_sort_dir = 'desc' then shipment_date end desc,
            case when p_sort_by = 'id' and p_sort_dir = 'asc' then id end asc,
            case when p_sort_by = 'id' and p_sort_dir = 'desc' then id end desc,
            case when p_sort_by = 'revenue' and p_sort_dir = 'asc' then recognized_revenue end asc,
            case when p_sort_by = 'revenue' and p_sort_dir = 'desc' then recognized_revenue end desc,
            case when p_sort_by = 'route' and p_sort_dir = 'asc' then route_label end asc,
            case when p_sort_by = 'route' and p_sort_dir = 'desc' then route_label end desc,
            id desc
        limit p_page_size
        offset (p_page - 1) * p_page_size
    )
    select jsonb_build_object(
        'summary', jsonb_build_object(
            'total_revenue', current_summary.total_revenue,
            'eligible_trips', current_summary.eligible_trips,
            'average_revenue', case when current_summary.eligible_trips = 0
                then null
                else round(current_summary.total_revenue / current_summary.eligible_trips, 2)
            end,
            'top_route', (
                select jsonb_build_object('label', route_label, 'revenue', revenue, 'trips', trips)
                from route_stats
                order by revenue desc, route_label
                limit 1
            ),
            'previous_revenue', previous_summary.total_revenue,
            'revenue_change_percent', case
                when previous_summary.total_revenue = 0 then null
                else round(
                    ((current_summary.total_revenue - previous_summary.total_revenue)
                    / previous_summary.total_revenue) * 100,
                    2
                )
            end
        ),
        'expenses', jsonb_build_object(
            'fuel_cost', fuel_stats.recorded_cost,
            'fuel_log_count', fuel_stats.log_count,
            'fuel_missing_cost_count', fuel_stats.missing_cost_count,
            'payroll_cost', payroll_stats.recorded_cost,
            'payroll_recorded_trip_count', payroll_stats.recorded_trip_count,
            'maintenance_cost', maintenance_stats.recorded_cost,
            'maintenance_record_count', maintenance_stats.record_count,
            'other_operating_expenses_available', false,
            'net_operating_revenue', case
                when nullif(trim(coalesce(p_origin, '')), '') is null
                 and nullif(trim(coalesce(p_destination, '')), '') is null
                 and p_route_number is null
                 and p_driver_id is null
                 and p_trailer_id is null
                 and p_pallet_capacity is null
                 and nullif(trim(coalesce(p_search, '')), '') is null
                then (
                    current_summary.total_revenue
                    - fuel_stats.recorded_cost
                    - payroll_stats.recorded_cost
                    - maintenance_stats.recorded_cost
                )::numeric(14, 2)
                else null
            end,
            'net_operating_revenue_available',
                nullif(trim(coalesce(p_origin, '')), '') is null
                and nullif(trim(coalesce(p_destination, '')), '') is null
                and p_route_number is null
                and p_driver_id is null
                and p_trailer_id is null
                and p_pallet_capacity is null
                and nullif(trim(coalesce(p_search, '')), '') is null,
            'scope_note',
                'Fuel and maintenance follow the date range and truck filter. Payroll includes reviewed or finalized trip items only. General operating expenses are not stored in the current schema; net is provisional and unavailable for route, driver, trailer, capacity, or text-search filtered views.'
        ),
        'trend', coalesce((
            select jsonb_agg(jsonb_build_object(
                'date', bucket_date,
                'revenue', revenue,
                'trips', trips
            ) order by bucket_date)
            from trend_stats
        ), '[]'::jsonb),
        'by_route', coalesce((
            select jsonb_agg(to_jsonb(routes) order by revenue desc, route_label)
            from (
                select route_label, route_number, origin, destination, revenue, trips
                from route_stats
                order by revenue desc, route_label
            ) as routes
        ), '[]'::jsonb),
        'by_driver', coalesce((
            select jsonb_agg(to_jsonb(drivers) order by revenue desc, driver_name)
            from (
                select driver_id, driver_name, revenue, trips
                from driver_stats
                order by revenue desc, driver_name
                limit 12
            ) as drivers
        ), '[]'::jsonb),
        'by_capacity', coalesce((
            select jsonb_agg(to_jsonb(capacities) order by pallet_capacity nulls last)
            from (
                select pallet_capacity, revenue, trips
                from capacity_stats
                order by pallet_capacity nulls last
            ) as capacities
        ), '[]'::jsonb),
        'by_truck', coalesce((
            select jsonb_agg(to_jsonb(trucks) order by revenue desc, truck_plate_number)
            from (
                select truck_id, truck_plate_number, revenue, trips
                from truck_stats
                order by revenue desc, truck_plate_number
                limit 12
            ) as trucks
        ), '[]'::jsonb),
        'by_trailer', coalesce((
            select jsonb_agg(to_jsonb(trailers) order by revenue desc, trailer_plate_number)
            from (
                select trailer_id, trailer_plate_number, revenue, trips
                from trailer_stats
                order by revenue desc, trailer_plate_number
                limit 12
            ) as trailers
        ), '[]'::jsonb),
        'by_truck_trailer', coalesce((
            select jsonb_agg(to_jsonb(assets) order by revenue desc, truck_plate_number, trailer_plate_number)
            from (
                select truck_id, truck_plate_number, trailer_id, trailer_plate_number, revenue, trips
                from truck_trailer_stats
                order by revenue desc, truck_plate_number, trailer_plate_number
                limit 12
            ) as assets
        ), '[]'::jsonb),
        'recent_trips', coalesce((
            select jsonb_agg(to_jsonb(trips) order by shipment_date desc, id desc)
            from recent_trips as trips
        ), '[]'::jsonb),
        'trip_volume', coalesce((
            select jsonb_agg(jsonb_build_object('date', bucket_date, 'trips', trips) order by bucket_date)
            from trend_stats
        ), '[]'::jsonb),
        'ledger', jsonb_build_object(
            'page', p_page,
            'page_size', p_page_size,
            'total', ledger_count.total,
            'items', coalesce((
                select jsonb_agg(jsonb_build_object(
                    'id', item.id,
                    'shipment_date', item.shipment_date,
                    'ism_no', item.ism_no,
                    'origin', item.origin,
                    'destination', item.destination,
                    'route_number', item.route_number,
                    'route_pair', item.route_pair,
                    'driver_id', item.driver_id,
                    'driver_name', item.driver_name,
                    'truck_id', item.truck_id,
                    'truck_plate_number', item.truck_plate_number,
                    'trailer_id', item.trailer_id,
                    'trailer_plate_number', item.trailer_plate_number,
                    'pallet_capacity', item.pallet_capacity,
                    'applied_rate', item.truck_route_rate,
                    'revenue_status', item.revenue_status,
                    'revenue_eligible', item.is_revenue_eligible,
                    'adjustments', item.adjustment_total,
                    'adjustment_details', item.adjustment_details,
                    'recognized_revenue', item.recognized_revenue
                ) order by item.shipment_date desc, item.id desc)
                from ledger_page as item
            ), '[]'::jsonb)
        )
    )
    into output
    from current_summary
    cross join previous_summary
    cross join ledger_count
    cross join fuel_stats
    cross join maintenance_stats
    cross join payroll_stats;

    return output;
end;
