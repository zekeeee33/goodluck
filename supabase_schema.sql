create table if not exists public.vehicles (
    id bigint generated by default as identity primary key,
    plate_number text not null unique,
    make text not null,
    model text not null,
    year integer not null check (year >= 1900),
    color text,
    status text not null default 'available',
    odometer bigint not null default 0 check (odometer >= 0),
    registration_expiry date,
    insurance_expiry date,
    created_at timestamptz not null default now()
);

create table if not exists public.trailers (
    id bigint generated by default as identity primary key,
    plate_number text not null unique,
    pallet_capacity integer check (pallet_capacity is null or pallet_capacity > 0),
    capacity_review_required boolean not null default true,
    year_model integer check (year_model is null or year_model >= 1900),
    make_model text,
    mv_file_no text,
    engine_no text,
    chassis_no text,
    trailer_type text,
    status text not null default 'active'
        check (status in ('active', 'inactive', 'maintenance')),
    remarks text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint trailers_capacity_review_consistency_check
        check (capacity_review_required = (pallet_capacity is null))
);

create table if not exists public.truck_routes (
    id bigint generated by default as identity primary key,
    route_number integer not null unique,
    origin_code text not null,
    destination_code text not null,
    origin_name text not null,
    destination_name text not null,
    route_pair text not null,
    fuel_allocation numeric(12, 2) check (fuel_allocation is null or fuel_allocation >= 0),
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint truck_routes_direction_unique unique (origin_code, destination_code),
    constraint truck_routes_distinct_locations check (origin_code <> destination_code)
);

create table if not exists public.truck_route_rates (
    id bigint generated by default as identity primary key,
    route_id bigint references public.truck_routes(id) on delete set null,
    origin_code text not null,
    destination_code text not null,
    pallet_capacity integer not null check (pallet_capacity > 0),
    hauling_rate numeric(12, 2) check (hauling_rate is null or hauling_rate >= 0),
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint truck_route_rates_direction_capacity_unique
        unique (origin_code, destination_code, pallet_capacity)
);

create index if not exists truck_route_rates_origin_destination_idx
    on public.truck_route_rates(origin_code, destination_code, pallet_capacity);
create unique index if not exists truck_route_rates_route_capacity_unique
    on public.truck_route_rates(route_id, pallet_capacity)
    where route_id is not null;

create table if not exists public.drivers (
    id bigint generated by default as identity primary key,
    name text not null,
    license_number text not null unique,
    phone text,
    email text,
    status text not null default 'active',
    created_at timestamptz not null default now()
);

create table if not exists public.assignments (
    id bigint generated by default as identity primary key,
    driver_id bigint not null references public.drivers(id) on delete cascade,
    vehicle_id bigint not null references public.vehicles(id) on delete cascade,
    assigned_date date not null default current_date,
    returned_date date,
    notes text
);

create table if not exists public.maintenance (
    id bigint generated by default as identity primary key,
    vehicle_id bigint not null references public.vehicles(id) on delete cascade,
    service_type text not null,
    description text,
    cost numeric(12, 2) not null default 0 check (cost >= 0),
    performed_on date not null default current_date
);

create table if not exists public.fuel_logs (
    id bigint generated by default as identity primary key,
    vehicle_id bigint not null references public.vehicles(id) on delete cascade,
    trip_id bigint references public.trips(id) on delete set null,
    fuel_type text not null default 'diesel',
    quantity numeric(12, 2) check (quantity is null or quantity > 0),
    price_per_liter numeric(12, 2) check (price_per_liter is null or price_per_liter > 0),
    total_cost numeric(12, 2) check (total_cost is null or total_cost >= 0),
    fuel_allocation numeric(12, 2) check (fuel_allocation is null or fuel_allocation >= 0),
    actual_expense numeric(12, 2) check (actual_expense is null or actual_expense >= 0),
    invoice_object_path text,
    remarks text,
    logged_on date not null default current_date
);

create table if not exists public.trips (
    id bigint generated by default as identity primary key,
    vehicle_id bigint references public.vehicles(id) on delete set null,
    driver_id bigint references public.drivers(id) on delete set null,
    record_date date,
    ism_no text,
    shipment_date date not null default current_date,
    time_in time without time zone,
    time_out time without time zone,
    origin text,
    destination text,
    route_id bigint references public.truck_routes(id) on delete set null,
    truck_id bigint references public.vehicles(id) on delete set null,
    trailer_id bigint references public.trailers(id) on delete set null,
    route_number integer,
    route_pair text,
    pallet_capacity integer check (pallet_capacity > 0),
    truck_route_rate_id bigint references public.truck_route_rates(id) on delete set null,
    truck_route_rate numeric(12, 2),
    trip_rate_review_required boolean not null default true,
    trailer_review_required boolean not null default true,
    plate_no text,
    load_details text,
    driver_name text,
    trip_fuel text,
    route text,
    start_odometer bigint check (start_odometer >= 0),
    end_odometer bigint check (
        start_odometer is null
        or end_odometer is null
        or end_odometer >= start_odometer
    ),
    trip_date date,
    notes text
);

create index if not exists assignments_vehicle_id_idx on public.assignments(vehicle_id);
create index if not exists assignments_driver_id_idx on public.assignments(driver_id);
create index if not exists maintenance_vehicle_id_idx on public.maintenance(vehicle_id);
create index if not exists fuel_logs_vehicle_id_idx on public.fuel_logs(vehicle_id);
create unique index if not exists fuel_logs_trip_id_unique on public.fuel_logs(trip_id) where trip_id is not null;
create index if not exists fuel_logs_trip_id_idx on public.fuel_logs(trip_id);
create index if not exists trips_vehicle_id_idx on public.trips(vehicle_id);
create index if not exists trips_driver_id_idx on public.trips(driver_id);
create index if not exists trips_shipment_date_idx on public.trips(shipment_date desc);
create index if not exists trips_route_id_idx on public.trips(route_id);
create index if not exists trips_truck_id_idx on public.trips(truck_id);
create index if not exists trips_trailer_id_idx on public.trips(trailer_id);
create index if not exists trips_trip_rate_review_required_idx
    on public.trips(trip_rate_review_required)
    where trip_rate_review_required;

