-- Truck hauling rates are separate from payroll and must retain directional, capacity-specific values.
create table if not exists public.truck_route_rates (
    id bigint generated by default as identity primary key,
    origin_code text not null,
    destination_code text not null,
    pallet_capacity integer not null check (pallet_capacity in (36, 46)),
    hauling_rate numeric(12, 2) not null check (hauling_rate >= 0),
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint truck_route_rates_direction_capacity_unique
        unique (origin_code, destination_code, pallet_capacity)
);

create index if not exists truck_route_rates_origin_destination_idx
    on public.truck_route_rates(origin_code, destination_code, pallet_capacity);

