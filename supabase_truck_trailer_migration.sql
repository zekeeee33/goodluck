-- Historical vehicle links establish the truck assignment, but there is no
-- reliable trailer identity in the prior schema, so leave trailer_id NULL.
update public.trips
set truck_id = vehicle_id
where truck_id is null and vehicle_id is not null;

create table if not exists public.legacy_vehicle_capacity_review (
    vehicle_id bigint primary key,
    plate_number text,
    previous_pallet_capacity integer,
    review_status text not null default 'unresolved',
    copied_at timestamptz not null default now()
);

create table if not exists public.legacy_trip_rate_review (
    trip_id bigint primary key,
    previous_route_id bigint,
    previous_route_number integer,
    previous_route_pair text,
    previous_pallet_capacity integer,
    previous_truck_route_rate_id bigint,
    previous_truck_route_rate numeric(12, 2),
    review_status text not null default 'unresolved',
    captured_at timestamptz not null default now()
);

-- Preserve any former vehicle capacity values for manual review before
-- removing the invalid capacity field from truck records. They are not
-- automatically turned into trailer assignments.
do $$
begin
    if exists (
        select 1 from information_schema.columns
        where table_schema = 'public'
          and table_name = 'vehicles'
          and column_name = 'pallet_capacity'
    ) then
        insert into public.legacy_vehicle_capacity_review
            (vehicle_id, plate_number, previous_pallet_capacity)
        select id, plate_number, pallet_capacity
        from public.vehicles
        where pallet_capacity is not null
        on conflict (vehicle_id) do update
            set plate_number = excluded.plate_number,
                previous_pallet_capacity = excluded.previous_pallet_capacity;

        alter table public.vehicles drop column pallet_capacity;
    end if;
end;
$$;

-- Earlier trip-rate snapshots may have used truck capacity. Preserve them for
-- audit, but do not present them as validated trailer-based hauling rates.
insert into public.legacy_trip_rate_review (
    trip_id,
    previous_route_id,
    previous_route_number,
    previous_route_pair,
    previous_pallet_capacity,
    previous_truck_route_rate_id,
    previous_truck_route_rate
)
select
    id,
    route_id,
    route_number,
    route_pair,
    pallet_capacity,
    truck_route_rate_id,
    truck_route_rate
from public.trips
where trailer_id is null
  and (
      route_id is not null
      or route_number is not null
      or route_pair is not null
      or pallet_capacity is not null
      or truck_route_rate_id is not null
      or truck_route_rate is not null
  )
on conflict (trip_id) do nothing;

update public.trips
