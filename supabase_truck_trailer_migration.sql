-- Treat the existing vehicles table as the truck registry to preserve its
-- current IDs and relationships. Trailer records are independent.
-- Apply after supabase_route_trip_rate_migration.sql.

create table if not exists public.trailers (
    id bigint generated by default as identity primary key,
    plate_number text not null unique,
    pallet_capacity integer check (pallet_capacity is null or pallet_capacity > 0),
    capacity_review_required boolean not null default true,
    year_model integer check (year_model is null or year_model >= 1900),
    make_model text,
    mv_file_no text,
    engine_no text,
    chassis_no text,
    trailer_type text,
    status text not null default 'active'
        check (status in ('active', 'inactive', 'maintenance')),
    remarks text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.trailers
    alter column pallet_capacity drop not null,
    drop constraint if exists trailers_pallet_capacity_check,
    add constraint trailers_pallet_capacity_check
        check (pallet_capacity is null or pallet_capacity > 0),
    add column if not exists capacity_review_required boolean not null default true,
    add column if not exists year_model integer,
    add column if not exists make_model text,
    add column if not exists mv_file_no text,
    add column if not exists engine_no text,
    add column if not exists chassis_no text;

update public.trailers
set capacity_review_required = (pallet_capacity is null),
    year_model = nullif(year_model, 0);

alter table public.trailers
    drop constraint if exists trailers_capacity_review_consistency_check;
alter table public.trailers
    add constraint trailers_capacity_review_consistency_check
        check (capacity_review_required = (pallet_capacity is null));

