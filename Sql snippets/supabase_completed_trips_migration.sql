) from public, anon, authenticated;
grant execute on function public.reopen_finalized_payroll_for_trip_transfer(
    bigint, date, uuid
) to service_role;

create or replace function public.reopen_finalized_payroll_period(
    p_period_id bigint,
    p_actor_id uuid
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
    selected_period public.payroll_periods%rowtype;
begin
    if p_period_id is null or p_actor_id is null then
        raise exception 'Payroll period and actor are required to reopen payroll';
    end if;

    select * into selected_period
    from public.payroll_periods
    where id = p_period_id
    for update;

    if not found then
        raise exception 'Payroll period not found';
    end if;
    if selected_period.status <> 'finalized' then
        raise exception 'Only finalized payroll can be reopened';
    end if;

    delete from public.payroll_summaries
    where payroll_period_id = selected_period.id;

    delete from public.payroll_items
    where payroll_period_id = selected_period.id;

    delete from public.overdraft_transactions
    where payroll_period_id = selected_period.id
      and transaction_type = 'deduction'
      and remarks = 'Payroll overdraft settlement';

    update public.payroll_periods
    set status = 'draft',
        reviewed_by = null,
        reviewed_at = null,
        finalized_by = null,
        finalized_at = null
    where id = selected_period.id;

    insert into public.payroll_audit (
        payroll_period_id, actor_id, action, details
    ) values (
        selected_period.id,
        p_actor_id,
        'reopened_for_regeneration',
        jsonb_build_object(
            'previous_status', 'finalized',
            'reason', 'manual_payroll_reopen'
        )
    );

    return jsonb_build_object(
        'period', jsonb_build_object(
            'id', selected_period.id,
            'start_date', selected_period.start_date,
            'end_date', selected_period.end_date
        )
    );
end;
$$;

revoke all on function public.reopen_finalized_payroll_period(
    bigint, uuid
) from public, anon, authenticated;
grant execute on function public.reopen_finalized_payroll_period(
    bigint, uuid
) to service_role;

