create or replace function public.reopen_finalized_payroll_for_trip_transfer(
    p_trip_id bigint,
    p_trip_date date,
    p_actor_id uuid
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
    selected_period record;
    reopened_periods jsonb := '[]'::jsonb;
begin
    if p_trip_id is null or p_trip_date is null or p_actor_id is null then
        raise exception 'Trip, trip date, and actor are required to reopen payroll';
    end if;

    for selected_period in
        select *
        from public.payroll_periods
        where status = 'finalized'
          and start_date <= p_trip_date
          and end_date >= p_trip_date
        order by id
        for update
    loop
        delete from public.payroll_summaries
        where payroll_period_id = selected_period.id;

        delete from public.payroll_items
        where payroll_period_id = selected_period.id;

        delete from public.overdraft_transactions
        where payroll_period_id = selected_period.id
          and transaction_type = 'deduction'
          and remarks = 'Payroll overdraft settlement';

        update public.payroll_periods
        set status = 'draft',
            reviewed_by = null,
            reviewed_at = null,
            finalized_by = null,
            finalized_at = null
        where id = selected_period.id;

        insert into public.payroll_audit (
            payroll_period_id, actor_id, action, details
        ) values (
            selected_period.id,
            p_actor_id,
            'reopened_for_trip_transfer',
            jsonb_build_object(
                'trip_id', p_trip_id,
                'trip_date', p_trip_date,
                'previous_status', 'finalized'
            )
        );

        reopened_periods := reopened_periods || jsonb_build_array(
            jsonb_build_object(
                'id', selected_period.id,
                'start_date', selected_period.start_date,
                'end_date', selected_period.end_date
            )
        );
    end loop;

    return jsonb_build_object('periods', reopened_periods);
end;
$$;

revoke all on function public.reopen_finalized_payroll_for_trip_transfer(
