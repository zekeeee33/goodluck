create or replace function public.prevent_completed_trip_owner_change()
returns trigger
language plpgsql
set search_path = pg_catalog, public, pg_temp
as $$
begin
    if new.owner_id is distinct from old.owner_id then
        raise exception 'Completed trip ownership cannot be changed';
    end if;
    new.updated_at := now();
    return new;
end;
$$;

