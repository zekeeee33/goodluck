    -- Stores an immutable snapshot for each administrator-generated payroll report.
    -- Run after supabase_payroll_migration.sql.

    create table if not exists public.generated_payroll_reports (
        id bigint generated by default as identity primary key,
        start_date date not null,
        end_date date not null,
        status text not null default 'draft'
            check (status in ('draft', 'reviewed', 'finalized')),
        filters jsonb not null default '{}'::jsonb,
        report_snapshot jsonb not null,
        trip_snapshot jsonb not null default '[]'::jsonb,
        driver_snapshot jsonb not null default '[]'::jsonb,
        driver_count integer not null default 0 check (driver_count >= 0),
        eligible_trip_count integer not null default 0 check (eligible_trip_count >= 0),
        gross_pay numeric(14, 2) not null default 0 check (gross_pay >= 0),
        net_payable numeric(14, 2) not null default 0 check (net_payable >= 0),
        generated_by uuid references auth.users(id) on delete set null,
        created_at timestamptz not null default now(),
        constraint generated_payroll_report_dates_check check (start_date <= end_date)
    );

    create index if not exists generated_payroll_reports_created_at_idx
        on public.generated_payroll_reports(created_at desc);

    alter table public.generated_payroll_reports enable row level security;

    revoke all on public.generated_payroll_reports from anon, authenticated;
    grant all on public.generated_payroll_reports to service_role;
    grant usage, select on sequence public.generated_payroll_reports_id_seq to service_role;
