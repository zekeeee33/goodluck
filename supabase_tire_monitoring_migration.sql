-- Apply after supabase_schema.sql and the truck/trailer migrations.
-- This migration is additive; it does not drop or recreate fleet data.

create sequence if not exists public.tire_monitoring_reference_seq;

create table if not exists public.tire_monitoring (
    id bigint generated by default as identity primary key,
    reference_no text not null unique default (
        'TIR-' || lpad(nextval('public.tire_monitoring_reference_seq')::text, 8, '0')
    ),
    asset_type text not null check (asset_type in ('truck', 'trailer')),
    vehicle_id bigint references public.vehicles(id) on delete restrict,
    trailer_id bigint references public.trailers(id) on delete restrict,
    replaces_tire_id bigint references public.tire_monitoring(id) on delete restrict,
    brand text not null,
    size text not null,
    tire_type text not null,
    serial_no text,
    supplier text,
    date_installed date not null,
    date_replaced date,
    remaining_lifespan_pct numeric(5, 2) not null default 100
        check (remaining_lifespan_pct between 0 and 100),
    reason text,
    remarks text,
    status text not null default 'installed'
        check (status in ('installed', 'replaced', 'removed')),
    created_at timestamptz not null default now(),
    created_by uuid references auth.users(id) on delete set null,
    updated_at timestamptz not null default now(),
    updated_by uuid references auth.users(id) on delete set null,
    constraint tire_monitoring_asset_assignment_check check (
        (asset_type = 'truck' and vehicle_id is not null and trailer_id is null)
        or (asset_type = 'trailer' and trailer_id is not null and vehicle_id is null)
    ),
    constraint tire_monitoring_lifecycle_check check (
        (status = 'installed' and date_replaced is null)
        or (
            status in ('replaced', 'removed')
            and date_replaced is not null
            and nullif(btrim(reason), '') is not null
        )
    ),
    constraint tire_monitoring_dates_check check (
        date_replaced is null or date_replaced >= date_installed
    )
);

alter table public.tire_monitoring
    add column if not exists replaces_tire_id bigint
        references public.tire_monitoring(id) on delete restrict;
alter table public.tire_monitoring
    add column if not exists remaining_lifespan_pct numeric(5, 2) not null default 100
        check (remaining_lifespan_pct between 0 and 100);

create unique index if not exists tire_monitoring_serial_no_unique
    on public.tire_monitoring (lower(btrim(serial_no)))
    where serial_no is not null and btrim(serial_no) <> '';
create index if not exists tire_monitoring_vehicle_status_idx
    on public.tire_monitoring (vehicle_id, status, date_installed desc);
create index if not exists tire_monitoring_trailer_status_idx
    on public.tire_monitoring (trailer_id, status, date_installed desc);
create index if not exists tire_monitoring_status_installed_idx
    on public.tire_monitoring (status, date_installed desc);
create index if not exists tire_monitoring_serial_no_idx
    on public.tire_monitoring (serial_no)
    where serial_no is not null;
create unique index if not exists tire_monitoring_replaces_tire_uidx
    on public.tire_monitoring (replaces_tire_id)
    where replaces_tire_id is not null;
create index if not exists tire_monitoring_created_by_idx
    on public.tire_monitoring (created_by, date_installed desc);

create table if not exists public.tire_monitoring_history (
    id bigint generated by default as identity primary key,
    tire_id bigint not null references public.tire_monitoring(id) on delete restrict,
    action text not null check (action in ('created', 'updated', 'replaced', 'removed')),
    actor_id uuid references auth.users(id) on delete set null,
    old_values jsonb,
    new_values jsonb not null,
    created_at timestamptz not null default now()
);
create index if not exists tire_monitoring_history_tire_created_idx
    on public.tire_monitoring_history (tire_id, created_at desc);

create or replace function public.protect_tire_monitoring_owner()
returns trigger
language plpgsql
set search_path = pg_catalog, public, pg_temp
as $$
begin
    if new.created_by is distinct from old.created_by then
        raise exception 'Tire record ownership cannot be changed';
    end if;
    new.updated_at := now();
    return new;
end;
$$;

drop trigger if exists tire_monitoring_owner_immutable on public.tire_monitoring;
create trigger tire_monitoring_owner_immutable
    before update on public.tire_monitoring
    for each row execute function public.protect_tire_monitoring_owner();

create or replace function public.log_tire_monitoring_history()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
    audit_action text;
    audit_actor uuid;
begin
    if tg_op = 'INSERT' then
        audit_action := 'created';
        audit_actor := new.created_by;
        insert into public.tire_monitoring_history (
            tire_id, action, actor_id, new_values
        )
        values (new.id, audit_action, audit_actor, to_jsonb(new));
        return new;
    end if;

    if new.status = 'replaced' and old.status <> 'replaced' then
        audit_action := 'replaced';
    elsif new.status = 'removed' and old.status <> 'removed' then
        audit_action := 'removed';
    else
        audit_action := 'updated';
    end if;
    audit_actor := new.updated_by;
    insert into public.tire_monitoring_history (
        tire_id, action, actor_id, old_values, new_values
    )
    values (new.id, audit_action, audit_actor, to_jsonb(old), to_jsonb(new));
    return new;
end;
$$;

drop trigger if exists tire_monitoring_audit on public.tire_monitoring;
create trigger tire_monitoring_audit
    after insert or update on public.tire_monitoring
    for each row execute function public.log_tire_monitoring_history();

create or replace view public.tire_monitoring_sheet
with (security_invoker = true)
as
select
    tire.id,
    tire.reference_no,
    tire.asset_type,
    tire.vehicle_id,
    tire.trailer_id,
    tire.brand,
    tire.size,
    tire.tire_type,
    tire.serial_no,
    tire.supplier,
    tire.date_installed,
    tire.date_replaced,
    null::integer as expected_lifespan_days,
    tire.reason,
    tire.remarks,
    tire.status,
    tire.created_at,
    tire.created_by,
    tire.updated_at,
    tire.updated_by,
    coalesce(vehicle.plate_number, trailer.plate_number) as plate_number,
    tire.remaining_lifespan_pct::numeric as remaining_lifespan_pct,
    tire.replaces_tire_id
from public.tire_monitoring as tire
left join public.vehicles as vehicle on vehicle.id = tire.vehicle_id
left join public.trailers as trailer on trailer.id = tire.trailer_id;

create or replace function public.get_tire_monitoring_summary(
    p_user_id uuid,
    p_warning_percent integer
)
returns table (
    total_records bigint,
    installed_tires bigint,
    near_end_tires bigint,
    replaced_tires bigint
)
language sql
stable
security invoker
set search_path = pg_catalog, public, pg_temp
as $$
    select
        count(*)::bigint,
        count(*) filter (where status = 'installed')::bigint,
        count(*) filter (
            where status = 'installed'
                and remaining_lifespan_pct <= p_warning_percent
        )::bigint,
        count(*) filter (where status = 'replaced')::bigint
    from public.tire_monitoring_sheet
    where p_user_id is null or created_by = p_user_id;
$$;

create or replace function public.replace_tire_monitoring(
    p_tire_id bigint,
    p_date_replaced date,
    p_reason text,
    p_brand text,
    p_size text,
    p_tire_type text,
    p_serial_no text,
    p_supplier text,
    p_remaining_lifespan_pct numeric,
    p_remarks text,
    p_actor_id uuid
)
returns table (old_record jsonb, new_record jsonb)
language plpgsql
security invoker
set search_path = pg_catalog, public, pg_temp
as $$
declare
    old_tire public.tire_monitoring%rowtype;
    replaced_tire public.tire_monitoring%rowtype;
    new_tire public.tire_monitoring%rowtype;
begin
    select * into old_tire
    from public.tire_monitoring
    where id = p_tire_id
    for update;

    if not found then
        raise exception 'Tire record % was not found', p_tire_id;
    end if;
    if old_tire.status <> 'installed' then
        raise exception 'Only an installed tire can be replaced';
    end if;
    if p_date_replaced < old_tire.date_installed then
        raise exception 'Replacement date cannot be before the installation date';
    end if;
    if nullif(btrim(p_reason), '') is null then
        raise exception 'A replacement reason is required';
    end if;
    if p_remaining_lifespan_pct is null
        or p_remaining_lifespan_pct < 0
        or p_remaining_lifespan_pct > 100 then
        raise exception 'Life span must be a percentage between 0 and 100';
    end if;

    update public.tire_monitoring
    set status = 'replaced',
        date_replaced = p_date_replaced,
        reason = btrim(p_reason),
        updated_by = p_actor_id
    where id = p_tire_id
    returning * into replaced_tire;

    insert into public.tire_monitoring (
        asset_type, vehicle_id, trailer_id, brand, size, tire_type,
        replaces_tire_id, serial_no, supplier, date_installed, remaining_lifespan_pct,
        remarks, status, created_by, updated_by
    )
    values (
        old_tire.asset_type, old_tire.vehicle_id, old_tire.trailer_id,
        btrim(p_brand), btrim(p_size), btrim(p_tire_type), old_tire.id,
        nullif(btrim(p_serial_no), ''), nullif(btrim(p_supplier), ''),
        p_date_replaced, p_remaining_lifespan_pct, nullif(btrim(p_remarks), ''),
        'installed', p_actor_id, p_actor_id
    )
    returning * into new_tire;

    return query
    select to_jsonb(replaced_tire), to_jsonb(new_tire);
end;
$$;

