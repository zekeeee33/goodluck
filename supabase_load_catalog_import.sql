    id bigint generated by default as identity primary key,
    section text not null,
    brand text not null,
    packing text not null default '',
    quantity integer,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    constraint load_catalog_quantity_nonnegative check (quantity is null or quantity >= 0),
    constraint load_catalog_section_brand_packing_key unique (section, brand, packing)
);

