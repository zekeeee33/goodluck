-- Migration: Fuel Allocation integration into Add Trip record
-- Adds route fuel allocation, links fuel logs to trips, enforces single fuel record per trip,
-- and creates fuel edit audit trail.
-- Apply after the base trips/routes schema and supabase_dispatcher_ownership_migration.sql.
-- Rerun this file when upgrading an existing project; CREATE TABLE IF NOT EXISTS does
-- not add trip_id to an already-existing fuel_logs table.

alter table public.truck_routes
    add column if not exists fuel_allocation numeric(12, 2) check (fuel_allocation is null or fuel_allocation >= 0);

alter table public.fuel_logs
    add column if not exists trip_id bigint references public.trips(id) on delete set null;

alter table public.fuel_logs
    add column if not exists fuel_allocation numeric(12, 2) check (fuel_allocation is null or fuel_allocation >= 0);

alter table public.fuel_logs
    add column if not exists actual_expense numeric(12, 2) check (actual_expense is null or actual_expense >= 0);

alter table public.fuel_logs
    add column if not exists remarks text;

alter table public.fuel_logs
    add column if not exists last_edited_by uuid references auth.users(id) on delete set null;

alter table public.fuel_logs
    add column if not exists last_edited_by_email text;

-- Allow quantity and price_per_liter to be optional for trip fuel records
alter table public.fuel_logs
    alter column quantity drop not null;

alter table public.fuel_logs
    alter column price_per_liter drop not null;

alter table public.fuel_logs
    alter column total_cost drop not null;

-- Enforce exactly one fuel record per trip to prevent duplicates
create unique index if not exists fuel_logs_trip_id_unique
    on public.fuel_logs(trip_id)
    where trip_id is not null;

create index if not exists fuel_logs_trip_id_idx
    on public.fuel_logs(trip_id);

-- Immutable audit history for fuel updates
create table if not exists public.fuel_edit_history (
    id bigint generated by default as identity primary key,
    fuel_id bigint not null references public.fuel_logs(id) on delete cascade,
    edited_by uuid references auth.users(id) on delete set null,
    edited_by_email text,
    edited_at timestamptz not null default now(),
    old_values jsonb not null,
    new_values jsonb not null
);

create index if not exists fuel_edit_history_fuel_id_edited_at_idx
    on public.fuel_edit_history(fuel_id, edited_at desc);

alter table public.fuel_edit_history enable row level security;

create or replace function public.log_fuel_edit_history()
returns trigger
language plpgsql
set search_path = pg_catalog, public, pg_temp
as $$
declare
    old_snapshot jsonb;
    new_snapshot jsonb;
begin
    old_snapshot := to_jsonb(old) - array[
        'created_by', 'last_edited_by', 'last_edited_by_email'
    ];
    new_snapshot := to_jsonb(new) - array[
        'created_by', 'last_edited_by', 'last_edited_by_email'
    ];

    if old_snapshot is distinct from new_snapshot then
        insert into public.fuel_edit_history (
            fuel_id,
            edited_by,
            edited_by_email,
            old_values,
            new_values
        )
        values (
            new.id,
            new.last_edited_by,
            new.last_edited_by_email,
            old_snapshot,
            new_snapshot
        );
    end if;
    return new;
end;
$$;

drop trigger if exists fuel_logs_edit_history on public.fuel_logs;
create trigger fuel_logs_edit_history
    after update on public.fuel_logs
    for each row execute function public.log_fuel_edit_history();

-- RLS policy for fuel_edit_history
drop policy if exists fuel_edit_history_select_dispatcher on public.fuel_edit_history;
create policy fuel_edit_history_select_dispatcher on public.fuel_edit_history
    for select
    using (
        exists (
            select 1 from public.fuel_logs fl
            where fl.id = fuel_edit_history.fuel_id
            and (
                auth.uid() = fl.created_by
                or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
                or (auth.jwt() -> 'user_metadata' ->> 'role') = 'admin'
            )
        )
    );
