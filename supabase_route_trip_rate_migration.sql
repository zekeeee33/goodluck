alter table public.truck_route_rates
    alter column hauling_rate drop not null,
    drop constraint if exists truck_route_rates_pallet_capacity_check,
    add constraint truck_route_rates_pallet_capacity_check
        check (pallet_capacity > 0),
    add column if not exists route_id bigint references public.truck_routes(id) on delete set null;

update public.truck_route_rates as rate
set route_id = route.id
from public.truck_routes as route
where rate.origin_code = route.origin_code
  and rate.destination_code = route.destination_code
  and rate.route_id is distinct from route.id;

create unique index if not exists truck_route_rates_route_capacity_unique
    on public.truck_route_rates(route_id, pallet_capacity)
    where route_id is not null;

