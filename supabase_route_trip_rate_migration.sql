alter table public.trips
    add column if not exists route_id bigint references public.truck_routes(id) on delete set null,
    add column if not exists route_number integer,
    add column if not exists route_pair text,
    add column if not exists pallet_capacity integer check (pallet_capacity > 0),
    add column if not exists truck_route_rate_id bigint references public.truck_route_rates(id) on delete set null,
    add column if not exists truck_route_rate numeric(12, 2),
    add column if not exists trip_rate_review_required boolean not null default true;

alter table public.trips
    drop constraint if exists trips_pallet_capacity_check;
alter table public.trips
    add constraint trips_pallet_capacity_check check (pallet_capacity > 0);

alter table public.payroll_items
    add column if not exists truck_route_rate numeric(12, 2);

update public.trips as trip
set route_id = route.id,
    route_number = route.route_number,
    route_pair = route.route_pair
from public.truck_routes as route
where upper(trim(trip.origin)) = route.origin_code
  and upper(trim(trip.destination)) = route.destination_code
  and trip.route_id is null;

create index if not exists trips_route_id_idx on public.trips(route_id);
create index if not exists trips_trip_rate_review_required_idx
    on public.trips(trip_rate_review_required)
    where trip_rate_review_required;

alter table public.truck_routes enable row level security;
alter table public.truck_route_rates enable row level security;
