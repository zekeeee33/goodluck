-- Apply after supabase_truck_route_rates_migration.sql,
-- supabase_trips_migration.sql, and supabase_payroll_migration.sql.

create table if not exists public.truck_routes (
    id bigint generated by default as identity primary key,
    route_number integer not null unique,
    origin_code text not null,
    destination_code text not null,
    origin_name text not null,
    destination_name text not null,
    route_pair text not null,
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint truck_routes_direction_unique unique (origin_code, destination_code),
    constraint truck_routes_distinct_locations check (origin_code <> destination_code)
);

